-- 5.1 create_invitation (psy) : crée un siège 'invited' avec un code unique.
create or replace function public.create_invitation(
  p_label text default null,
  p_invite_email text default null
) returns public.patient_seats
language plpgsql security definer set search_path = public as $$
declare v_seat public.patient_seats; v_code text; v_try int := 0;
begin
  if not exists (select 1 from public.practitioners where id = auth.uid()) then
    raise exception 'not_practitioner';
  end if;
  loop
    v_try := v_try + 1;
    v_code := public.gen_invite_code();
    begin
      insert into public.patient_seats (practitioner_id, label, invite_email, invite_code)
      values (auth.uid(), p_label, p_invite_email, v_code)
      returning * into v_seat;
      exit;
    exception when unique_violation then
      if v_try >= 10 then raise exception 'code_generation_failed'; end if;
    end;
  end loop;
  insert into public.audit_events(actor_user_id, action, target_seat_id)
    values (auth.uid(), 'invitation_created', v_seat.id);
  return v_seat;
end; $$;

-- 5.2 regenerate_code (psy) : nouveau code pour un siège 'invited' lui appartenant.
create or replace function public.regenerate_code(p_seat_id uuid)
returns public.patient_seats
language plpgsql security definer set search_path = public as $$
declare v_seat public.patient_seats; v_code text; v_try int := 0;
begin
  select * into v_seat from public.patient_seats
    where id = p_seat_id and practitioner_id = auth.uid() for update;
  if not found then raise exception 'not_owner'; end if;
  if v_seat.status <> 'invited' then raise exception 'seat_not_invited'; end if;
  loop
    v_try := v_try + 1; v_code := public.gen_invite_code();
    begin
      update public.patient_seats
        set invite_code = v_code, expires_at = now() + interval '30 days'
        where id = p_seat_id returning * into v_seat;
      exit;
    exception when unique_violation then
      if v_try >= 10 then raise exception 'code_generation_failed'; end if;
    end;
  end loop;
  insert into public.audit_events(actor_user_id, action, target_seat_id)
    values (auth.uid(), 'code_regenerated', p_seat_id);
  return v_seat;
end; $$;

-- 5.3 revoke_seat (psy) : met fin à un siège 'active' ou annule un 'invited'.
create or replace function public.revoke_seat(p_seat_id uuid)
returns public.patient_seats
language plpgsql security definer set search_path = public as $$
declare v_seat public.patient_seats;
begin
  select * into v_seat from public.patient_seats
    where id = p_seat_id and practitioner_id = auth.uid() for update;
  if not found then raise exception 'not_owner'; end if;
  if v_seat.status not in ('active','invited') then
    raise exception 'seat_not_active_or_invited';
  end if;
  update public.patient_seats set status = 'revoked', revoked_at = now()
    where id = p_seat_id returning * into v_seat;
  insert into public.audit_events(actor_user_id, action, target_seat_id)
    values (auth.uid(), 'seat_revoked', p_seat_id);
  return v_seat;
end; $$;

-- 5.4 redeem_seat_code (patient) : rattache ; bascule auto si déjà rattaché (RG-7).
create or replace function public.redeem_seat_code(p_code text)
returns public.patient_seats
language plpgsql security definer set search_path = public as $$
declare v_seat public.patient_seats;
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;

  select * into v_seat from public.patient_seats
    where upper(invite_code) = upper(p_code) for update;
  if not found then raise exception 'invalid_code'; end if;
  if v_seat.status <> 'invited' then raise exception 'code_already_used'; end if;
  if v_seat.expires_at < now() then
    update public.patient_seats set status = 'expired' where id = v_seat.id;
    raise exception 'code_expired';
  end if;

  -- Bascule : libère le siège actif courant du patient, s'il existe.
  update public.patient_seats
    set status = 'released', released_at = now()
    where patient_user_id = auth.uid() and status = 'active';

  update public.patient_seats
    set patient_user_id = auth.uid(), status = 'active', redeemed_at = now()
    where id = v_seat.id returning * into v_seat;

  insert into public.audit_events(actor_user_id, action, target_seat_id)
    values (auth.uid(), 'code_redeemed', v_seat.id);
  return v_seat;
end; $$;

-- 5.5 release_my_seat (patient) : se délie (RG-8).
create or replace function public.release_my_seat()
returns public.patient_seats
language plpgsql security definer set search_path = public as $$
declare v_seat public.patient_seats;
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;
  update public.patient_seats set status = 'released', released_at = now()
    where patient_user_id = auth.uid() and status = 'active'
    returning * into v_seat;
  if not found then raise exception 'no_active_seat'; end if;
  insert into public.audit_events(actor_user_id, action, target_seat_id)
    values (auth.uid(), 'seat_released', v_seat.id);
  return v_seat;
end; $$;

-- 5.6 record_completion (patient) : enregistre "fait" si rattaché actif (RG-6/11).
create or replace function public.record_completion(p_exercise_id bigint)
returns public.exercise_completions
language plpgsql security definer set search_path = public as $$
declare v_row public.exercise_completions;
begin
  if auth.uid() is null then raise exception 'not_authenticated'; end if;
  if not exists (
    select 1 from public.patient_seats where patient_user_id = auth.uid() and status = 'active'
  ) then raise exception 'no_active_seat'; end if;
  insert into public.exercise_completions(patient_user_id, exercise_id)
    values (auth.uid(), p_exercise_id) returning * into v_row;
  return v_row;
end; $$;

