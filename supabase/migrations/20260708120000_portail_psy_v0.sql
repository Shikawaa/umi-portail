create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end;
$$;

-- Génération d'un code lisible : UMI-XXXX-XX (alphabet sans 0/O/1/I/L)
create or replace function public.gen_invite_code()
returns text language plpgsql as $$
declare
  alphabet constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  n        constant int  := length('ABCDEFGHJKMNPQRSTUVWXYZ23456789');
  s text := '';
  i int;
begin
  for i in 1..6 loop
    s := s || substr(alphabet, 1 + floor(random() * n)::int, 1);
  end loop;
  return 'UMI-' || substr(s,1,4) || '-' || substr(s,5,2);
end;
$$;
-- Interne : ne pas exposer via l'API.
revoke all on function public.gen_invite_code() from public, anon, authenticated;

-- ----------------------------------------------------------------------------
-- 1. PRACTITIONERS (compte psy — minimal)
-- ----------------------------------------------------------------------------
create table if not exists public.practitioners (
  id                  uuid primary key references auth.users (id) on delete cascade,
  practitioner_number bigint generated by default as identity unique,   -- psy 1, 2, 3… (auto)
  first_name          text,
  last_name           text,
  locale              text not null default 'fr' check (locale in ('fr','en')),  -- langue portail
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

drop trigger if exists practitioners_set_updated_at on public.practitioners;
create trigger practitioners_set_updated_at
  before update on public.practitioners
  for each row execute function public.set_updated_at();

alter table public.practitioners enable row level security;

drop policy if exists practitioner_select_own on public.practitioners;
create policy practitioner_select_own on public.practitioners
  for select using (id = auth.uid());
drop policy if exists practitioner_insert_self on public.practitioners;
create policy practitioner_insert_self on public.practitioners
  for insert with check (id = auth.uid());
drop policy if exists practitioner_update_own on public.practitioners;
create policy practitioner_update_own on public.practitioners
  for update using (id = auth.uid()) with check (id = auth.uid());

-- ----------------------------------------------------------------------------
-- 2. PATIENT_SEATS (invitation + rattachement + futur siège de facturation)
-- ----------------------------------------------------------------------------
create table if not exists public.patient_seats (
  id               uuid primary key default gen_random_uuid(),
  practitioner_id  uuid not null references public.practitioners (id) on delete cascade,
  patient_user_id  uuid references auth.users (id) on delete set null,
  label            text,
  invite_code      text not null unique,
  invite_email     text,
  status           text not null default 'invited'
                     check (status in ('invited','active','paused','revoked','released','expired')),
  created_at       timestamptz not null default now(),
  expires_at       timestamptz not null default (now() + interval '30 days'),
  redeemed_at      timestamptz,
  revoked_at       timestamptz,
  released_at      timestamptz
);

create index if not exists patient_seats_practitioner_idx on public.patient_seats (practitioner_id);
create index if not exists patient_seats_patient_idx      on public.patient_seats (patient_user_id);
-- Un seul siège actif par patient (garantit RG-10 au niveau data).
create unique index if not exists patient_seats_one_active_per_patient
  on public.patient_seats (patient_user_id) where status = 'active';

alter table public.patient_seats enable row level security;

-- Le psy gère uniquement ses propres sièges.
drop policy if exists seat_practitioner_all on public.patient_seats;
create policy seat_practitioner_all on public.patient_seats
  for all using (practitioner_id = auth.uid())
  with check (practitioner_id = auth.uid());
-- Le patient lit le siège auquel il est rattaché.
drop policy if exists seat_patient_select on public.patient_seats;
create policy seat_patient_select on public.patient_seats
  for select using (patient_user_id = auth.uid());

-- ----------------------------------------------------------------------------
-- 3. EXERCISE_COMPLETIONS ("fait/non fait" — métadonnée, sans contenu)
-- ----------------------------------------------------------------------------
create table if not exists public.exercise_completions (
  id               uuid primary key default gen_random_uuid(),
  patient_user_id  uuid not null references auth.users (id) on delete cascade,
  exercise_id      bigint not null references public.exercises (id),
  completed_at     timestamptz not null default now()
);
create index if not exists exercise_completions_patient_idx
  on public.exercise_completions (patient_user_id, completed_at);

alter table public.exercise_completions enable row level security;

-- Le patient n'enregistre une complétion que s'il a un siège actif (RG-6).
drop policy if exists completion_patient_insert on public.exercise_completions;
create policy completion_patient_insert on public.exercise_completions
  for insert with check (
    patient_user_id = auth.uid()
    and exists (
      select 1 from public.patient_seats s
      where s.patient_user_id = auth.uid() and s.status = 'active'
    )
  );
-- Le patient lit les siennes.
drop policy if exists completion_patient_select on public.exercise_completions;
create policy completion_patient_select on public.exercise_completions
  for select using (patient_user_id = auth.uid());
-- Le psy lit celles d'un patient rattaché ACTIF, sur la PÉRIODE de rattachement (RG-14).
drop policy if exists completion_practitioner_select on public.exercise_completions;
create policy completion_practitioner_select on public.exercise_completions
  for select using (
    exists (
      select 1 from public.patient_seats s
      where s.patient_user_id = exercise_completions.patient_user_id
        and s.practitioner_id = auth.uid()
        and s.status = 'active'
        and exercise_completions.completed_at >= s.redeemed_at
    )
  );

-- ----------------------------------------------------------------------------
-- 4. AUDIT_EVENTS (traçabilité des actions sensibles) — accès via fonctions only
-- ----------------------------------------------------------------------------
create table if not exists public.audit_events (
  id             uuid primary key default gen_random_uuid(),
  actor_user_id  uuid,
  action         text not null,
  target_seat_id uuid,
  created_at     timestamptz not null default now()
);
alter table public.audit_events enable row level security;
-- Aucune policy => aucun accès direct (les fonctions security definer y écrivent).

